export const METRIC_GROUP_MAP: Record<string, MetricGroupDef> = Object.fromEntries(
  METRIC_GROUPS.map((g) => [g.group, g])
)

/** Reverse lookup: metric code → group string. Each expanded metric declares its own
 *  group inline; original core-registry metrics are mapped here too for consistency. */
export const METRIC_CODE_TO_GROUP: Record<string, string> = (() => {
  const out: Record<string, string> = {} as Record<string, string>
  for (const g of METRIC_GROUPS) {
    for (const code of g.metrics) {
      if (!out[code]) out[code] = g.group
    }
  }
  // Pull from expanded metric inline declarations too (some metrics appear in a
  // group not listed above; their inline `group` field is canonical).
  for (const m of EXPANDED_METRICS) {
    if (m.group && !out[m.code]) out[m.code] = m.group
  }
  return out
})()

/** Resolve the metric group for a metric code (returns undefined for unmapped). */
export function getMetricGroup(code: string): MetricGroupDef | undefined {
  const g = METRIC_CODE_TO_GROUP[code]
  return g ? METRIC_GROUP_MAP[g] : undefined
}
